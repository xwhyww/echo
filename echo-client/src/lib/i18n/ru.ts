/**
 * Russian plural picker: 1 приглашение / 2 приглашения / 5 приглашений.
 * `few` covers 2–4, `many` covers 0, 5–20 and everything ending in 0 or 5–9.
 */
function plural(n: number, one: string, few: string, many: string): string {
	const mod100 = n % 100;
	if (mod100 >= 11 && mod100 <= 14) return many;
	const mod10 = n % 10;
	if (mod10 === 1) return one;
	if (mod10 >= 2 && mod10 <= 4) return few;
	return many;
}

